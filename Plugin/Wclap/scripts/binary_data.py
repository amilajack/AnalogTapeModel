#!/usr/bin/env python3
"""Write BinaryData.h and BinaryData.cpp as JUCE's juceaide would.

The WCLAP build compiles JUCE's modules directly, without juceaide (JUCE 6.1's
juceaide no longer builds against current macOS SDKs, and it is a native tool
in a cross build). Names follow juce_build_tools::makeBinaryDataIdentifierName,
so the plug-in sources use the same BinaryData:: symbols as the desktop build.

usage: binary_data.py OUT_DIR FILE...
"""
import pathlib
import re
import sys


def identifier(file_name: str) -> str:
    # makeBinaryDataIdentifierName: spaces and dots become underscores and
    # anything else that is not [A-Za-z0-9_] is dropped. makeValidIdentifier
    # then only splits and rejoins words, which leaves the name unchanged.
    name = re.sub(r"[^A-Za-z0-9_]", "", file_name.replace(" ", "_").replace(".", "_"))
    if not name:
        return "unknown"
    if name[0].isdigit():
        name = "_" + name
    return name


def main() -> None:
    out = pathlib.Path(sys.argv[1])
    files = [pathlib.Path(p) for p in sys.argv[2:]]
    names = []
    for f in files:
        root = identifier(f.name)
        name, suffix = root, 2
        while name in names:
            name = f"{root}{suffix}"
            suffix += 1
        names.append(name)

    header = ["/* Generated by Plugin/Wclap/scripts/binary_data.py. Do not edit. */",
              "#pragma once", "", "namespace BinaryData", "{"]
    for f, name in zip(files, names):
        header.append(f"    extern const char*   {name};")
        header.append(f"    const int            {name}Size = {f.stat().st_size};")
        header.append("")
    header += [
        f"    const int namedResourceListSize = {len(files)};",
        "    extern const char* namedResourceList[];",
        "    extern const char* originalFilenames[];",
        "    const char* getNamedResource (const char* resourceNameUTF8, int& dataSizeInBytes);",
        "    const char* getNamedResourceOriginalFilename (const char* resourceNameUTF8);",
        "}", ""]

    cpp = ["/* Generated by Plugin/Wclap/scripts/binary_data.py. Do not edit. */",
           "#include \"BinaryData.h\"", "#include <cstring>", "", "namespace BinaryData", "{"]
    for i, (f, name) in enumerate(zip(files, names)):
        data = f.read_bytes() + b"\0"  # juceaide also terminates each resource
        cpp.append(f"static const unsigned char temp_binary_data_{i}[] = {{")
        for start in range(0, len(data), 32):
            cpp.append(",".join(str(b) for b in data[start:start + 32]) + ",")
        cpp.append("};")
        cpp.append(f"const char* {name} = (const char*) temp_binary_data_{i};")
        cpp.append("")
    cpp.append("const char* namedResourceList[] = {")
    cpp += [f"    \"{n}\"," for n in names]
    cpp.append("};")
    cpp.append("const char* originalFilenames[] = {")
    cpp += ["    \"" + f.name.replace("\\", "\\\\").replace("\"", "\\\"") + "\"," for f in files]
    cpp.append("};")
    cpp += [
        "const char* getNamedResource (const char* resourceNameUTF8, int& numBytes)",
        "{",
    ]
    for f, name in zip(files, names):
        cpp.append(f"    if (std::strcmp (resourceNameUTF8, \"{name}\") == 0) {{ numBytes = {f.stat().st_size}; return {name}; }}")
    cpp += [
        "    numBytes = 0;",
        "    return nullptr;",
        "}",
        "const char* getNamedResourceOriginalFilename (const char* resourceNameUTF8)",
        "{",
        "    for (int i = 0; i < namedResourceListSize; ++i)",
        "        if (std::strcmp (namedResourceList[i], resourceNameUTF8) == 0)",
        "            return originalFilenames[i];",
        "    return nullptr;",
        "}",
        "}", ""]

    out.mkdir(parents=True, exist_ok=True)
    for path, text in ((out / "BinaryData.h", "\n".join(header)), (out / "BinaryData.cpp", "\n".join(cpp))):
        if not path.exists() or path.read_text() != text:
            path.write_text(text)


if __name__ == "__main__":
    main()
